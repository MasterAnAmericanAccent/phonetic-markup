import { writeFile } from 'node:fs/promises'
import { expect, test, type Page } from '@playwright/test'
import { pngBytes, pngSize, readEditor, replaceWith, scanPng, selectVisibleText } from './helpers'

async function add(page: Page, character: string, category = 'vowel') {
  await page.getByRole('button', { name: '+ Add IPA', exact: true }).click()
  await page.getByRole('textbox', { name: 'Unicode character' }).fill(character)
  await page.getByLabel('Category', { exact: true }).selectOption(category)
  await page.getByRole('button', { name: 'Save', exact: true }).click()
}

for (const [category, label] of [['vowel', 'Vowels'], ['consonant', 'Consonants'], ['intonation', 'Intonation']]) {
  test(`adds, restores and removes custom characters in ${label}`, async ({ page, context }) => {
    await page.goto('/')
    await add(page, 'ɐ', category)
    await expect(page.getByRole('tab', { name: label, exact: true })).toHaveAttribute('aria-selected', 'true')
    const button = page.getByRole('button', { name: 'Insert ɐ, U+0250', exact: true })
    await expect(button).toHaveCount(1)
    await expect(page.getByText('Custom characters are saved only in this browser on this device.', { exact: false })).toHaveCount(0)
    await page.reload()
    await page.getByRole('tab', { name: label, exact: true }).click()
    await expect(button).toHaveCount(1)
    const reopened = await context.newPage()
    await reopened.goto('http://127.0.0.1:5175/')
    await reopened.getByRole('tab', { name: label, exact: true }).click()
    await expect(reopened.getByRole('button', { name: 'Insert ɐ, U+0250', exact: true })).toHaveCount(1)
    await reopened.close()
    await page.getByRole('button', { name: '− Remove IPA', exact: true }).click()
    await page.screenshot({ path: test.info().outputPath('custom-ipa-form.png') })
    await page.getByRole('button', { name: `Remove custom ɐ from ${category}`, exact: true }).click()
    await page.getByRole('group', { name: 'Confirm IPA removal' }).getByRole('button', { name: 'Remove', exact: true }).click()
    await expect(button).toHaveCount(0)
    await page.reload()
    await page.getByRole('tab', { name: label, exact: true }).click()
    await expect(button).toHaveCount(0)
    await page.getByRole('tab', { name: 'Vowels', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Insert ǣ, U+01E3', exact: true })).toHaveCount(1)
  })
}

test('rejects duplicates and protects built-ins while preserving custom editor/export behavior', async ({ page }) => {
  await page.goto('/')
  await add(page, 'ǣ')
  await expect(page.getByRole('alert')).toContainText('already exists')
  await expect(page.getByRole('button', { name: /Remove custom ǣ/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await replaceWith(page, 'Say this now.')
  await selectVisibleText(page, 'Say')
  await page.keyboard.press('ArrowRight')
  await add(page, 'ɐ')
  await page.waitForTimeout(600) // isolate fixture typing from insertion history
  await page.getByRole('button', { name: 'Insert ɐ, U+0250', exact: true }).click()
  expect((await readEditor(page)).text).toBe('Sayɐ this now.')
  await expect(page.locator('.ProseMirror')).toBeFocused()
  await expect(page.locator('.ProseMirror [data-ipa-offset]')).toHaveCSS('vertical-align', 'super')
  await expect(page.locator('.ProseMirror [data-ipa-offset]')).toHaveCSS('font-size', '30px')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  expect((await readEditor(page)).text).toBe('Say this now.')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await page.keyboard.type('!')
  expect((await readEditor(page)).text).toBe('Sayɐ! this now.')
  await expect(page.locator('.ProseMirror [data-ipa-offset]')).toHaveText('ɐ')
  await page.waitForTimeout(600)
  await selectVisibleText(page, 'ɐ')
  await page.keyboard.type('x')
  expect((await readEditor(page)).text).toBe('Sayx! this now.')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  expect((await readEditor(page)).text).toBe('Sayɐ! this now.')
  await add(page, 'ɐ')
  await expect(page.getByRole('alert')).toContainText('already exists')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Insert ɐ, U+0250', exact: true })).toHaveCount(1)
  const bytes = await pngBytes(page)
  expect(pngSize(bytes).signature).toBe('89504e470d0a1a0a')
  expect((await scanPng(page, bytes)).ink).toBeGreaterThan(100)
  await writeFile(test.info().outputPath('custom-ipa.png'), bytes)
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export HTML', exact: true }).click()])
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  await page.getByRole('button', { name: '− Remove IPA', exact: true }).click()
  await page.getByRole('button', { name: 'Remove custom ɐ from vowel', exact: true }).click()
  await page.getByRole('group', { name: 'Confirm IPA removal' }).getByRole('button', { name: 'Remove', exact: true }).click()
  expect((await readEditor(page)).text).toBe('Sayɐ! this now.')
  await expect(page.getByRole('button', { name: 'Insert ɐ, U+0250', exact: true })).toHaveCount(0)
  await page.setContent(Buffer.concat(chunks).toString('utf8'))
  await expect(page.locator('article')).toHaveText('Sayɐ! this now.')
  await expect(page.locator('[data-ipa-offset]')).toHaveText('ɐ')
  await expect(page.locator('[data-ipa-offset]')).toHaveCSS('vertical-align', 'super')
})

test('reports storage failure without claiming the character was saved', async ({ page }) => {
  await page.addInitScript(() => { Storage.prototype.setItem = () => { throw new Error('blocked') } })
  await page.goto('/')
  await add(page, 'ɐ')
  await expect(page.getByRole('alert')).toContainText('No changes were saved')
  await expect(page.getByRole('button', { name: 'Insert ɐ, U+0250', exact: true })).toHaveCount(0)
  await expect(page.getByRole('form', { name: 'Add or manage custom IPA' })).toBeVisible()
})

test('removal mode protects built-ins, supports cancel/done, and requires confirmation', async ({ page }) => {
  await page.goto('/')
  const remove = page.getByRole('button', { name: '− Remove IPA', exact: true })
  await expect(remove).toBeDisabled()
  const addBox = (await page.getByRole('button', { name: '+ Add IPA', exact: true }).boundingBox())!
  const removeBox = (await remove.boundingBox())!
  expect(removeBox.y).toBeCloseTo(addBox.y, 1)
  expect(removeBox.x).toBeGreaterThanOrEqual(addBox.x + addBox.width)
  await add(page, 'ɐ')
  await add(page, 'ɲ', 'consonant')
  await page.getByRole('tab', { name: 'Vowels', exact: true }).click()
  const before = await readEditor(page)
  await remove.click()
  await expect(page.getByRole('button', { name: 'Insert ǣ, U+01E3', exact: true })).toBeDisabled()
  const custom = page.getByRole('button', { name: 'Remove custom ɐ from vowel', exact: true })
  await custom.click()
  const confirm = page.getByRole('group', { name: 'Confirm IPA removal' })
  await expect(confirm).toContainText('Remove ɐ from Vowels?')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.screenshot({ path: test.info().outputPath('removal-confirmation.png') })
  await expect(custom).toHaveCount(1)
  expect((await readEditor(page)).text).toBe(before.text)
  await confirm.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(confirm).toHaveCount(0)
  await expect(custom).toHaveCount(1)
  await custom.click()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(confirm).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Insert ɐ, U+0250', exact: true })).toBeEnabled()
  await remove.click()
  await page.getByRole('button', { name: 'Remove custom ɐ from vowel', exact: true }).click()
  await page.getByRole('tab', { name: 'Consonants', exact: true }).click()
  await expect(confirm).toHaveCount(0)
  await page.getByRole('button', { name: 'Remove custom ɲ from consonant', exact: true }).click()
  await confirm.getByRole('button', { name: 'Remove', exact: true }).click()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Insert ɐ, U+0250', exact: true })).toHaveCount(1)
  await page.getByRole('tab', { name: 'Consonants', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Insert ɲ, U+0272', exact: true })).toHaveCount(0)
  expect((await readEditor(page)).text).toBe(before.text)
})

test('failed removal preserves the custom entry and offers cancel', async ({ page }) => {
  await page.goto('/')
  await add(page, 'ɐ')
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('quota') } })
  await page.getByRole('button', { name: '− Remove IPA', exact: true }).click()
  const custom = page.getByRole('button', { name: 'Remove custom ɐ from vowel', exact: true })
  await custom.click()
  const confirm = page.getByRole('group', { name: 'Confirm IPA removal' })
  await confirm.getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('No changes were saved')
  await expect(custom).toHaveCount(1)
  await confirm.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Insert ɐ, U+0250', exact: true })).toHaveCount(1)
})
